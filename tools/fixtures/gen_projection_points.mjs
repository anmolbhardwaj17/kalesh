#!/usr/bin/env node
// Writes harness/data/fixtures/projection_points.json: 20 points (lat, lon, x, z) from the TypeScript projection
// (tools/geo/projection.ts, the reference for the offline bake tooling). The GDScript port (game/geo/projection.gd) is
// checked against this file in game/tests/test_projection.gd, and tools/geo/projection.fixture.test.ts checks the file
// still matches the TypeScript code. Rerun after any projection change:  node tools/fixtures/gen_projection_points.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { geoToWorld, ORIGIN } from '../geo/projection.ts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = path.join(ROOT, 'harness', 'data', 'fixtures', 'projection_points.json');

// Named places across Delhi and NCR, then the corners and edges of a 60 km box, so the series is checked far out too.
const PLACES = [
  ['India Gate (origin)', ORIGIN.lat, ORIGIN.lon],
  ['Connaught Place park', 28.6315, 77.2167],
  ['Red Fort', 28.6562, 77.241],
  ['Jantar Mantar', 28.62705, 77.21664],
  ['ITO crossing', 28.62855, 77.24135],
  ['Chandni Chowk', 28.6506, 77.2303],
  ['Humayun Tomb', 28.5933, 77.2507],
  ['Qutub Minar', 28.5245, 77.1855],
  ['IGI Airport T3', 28.5562, 77.1],
  ['Cyber City Gurugram', 28.495, 77.089],
  ['Akshardham', 28.6127, 77.2773],
  ['Laxmi Nagar', 28.6304, 77.2777],
  ['Kashmere Gate ISBT', 28.6676, 77.2283],
  ['Malcha Mahal', 28.5966, 77.1717],
  ['Noida Sector 18', 28.5708, 77.3261],
  ['due north 20 km', ORIGIN.lat + 0.1805, ORIGIN.lon],
  ['far north-east', 28.85, 77.45],
  ['far south-west', 28.4, 77.0],
  ['far north-west', 28.85, 77.0],
  ['far south-east', 28.4, 77.45],
];

const r = (v) => Math.round(v * 1e6) / 1e6;
const points = PLACES.map(([name, lat, lon]) => {
  const p = geoToWorld(lat, lon);
  return { name, lat, lon, x: r(p.x), z: r(p.z) };
});
const doc = {
  _doc: 'Generated by tools/fixtures/gen_projection_points.mjs from tools/geo/projection.ts. World metres: x east, z south (north is -Z), rounded to 1 micrometre. The GDScript port must match within 0.01 m.',
  origin: { lat: ORIGIN.lat, lon: ORIGIN.lon },
  points,
};
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, JSON.stringify(doc, null, 2) + '\n');
console.log(`wrote ${points.length} points to ${path.relative(ROOT, OUT)}`);
