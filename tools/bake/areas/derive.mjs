// Builds harness/data/areas/rule_cells.json (P2-004): the archetype of every 100 m cell of the pilot centre box, by the
// rules in rules.json, from the OSM land use polygons and the merged footprint grid. Reads the pilot data read only.
//   node tools/bake/areas/derive.mjs [--write]
// An .mjs script: it reads files; the pure rule code is tools/bake/areas/rules.ts.
import fs from 'node:fs';
const { geoToWorld } = await import('../../geo/projection.ts');
const { classifyCell, cellKey } = await import('./rules.ts');

const table = JSON.parse(fs.readFileSync('harness/data/areas/rules.json', 'utf8'));
const CELL = table.cell_m;
const graph = JSON.parse(fs.readFileSync('data/pilot_centre/graph.json', 'utf8'));
const osm = JSON.parse(fs.readFileSync('data/pilot_centre/osm.json', 'utf8'));
const pilot = JSON.parse(fs.readFileSync('harness/data/districts/pilot_centre.geojson', 'utf8')).features[0].geometry.coordinates[0].map(([lon, lat]) => geoToWorld(lat, lon));

const WANT = new Set(['landuse', 'leisure', 'natural', 'amenity', 'tourism', 'railway', 'historic']);
const nodes = new Map();
for (const e of osm.elements) if (e.type === 'node') nodes.set(e.id, geoToWorld(e.lat, e.lon));
const polys = [];
for (const e of osm.elements) {
  if (e.type !== 'way' || !e.tags || e.nodes[0] !== e.nodes[e.nodes.length - 1] || e.nodes.length < 4) continue;
  const tags = Object.entries(e.tags).filter(([k]) => WANT.has(k)).map(([k, v]) => `${k}=${v}`);
  if (!tags.length) continue;
  const ring = e.nodes.map((i) => nodes.get(i));
  if (ring.some((p) => !p)) continue;
  let x0 = Infinity, x1 = -Infinity, z0 = Infinity, z1 = -Infinity;
  for (const p of ring) { x0 = Math.min(x0, p.x); x1 = Math.max(x1, p.x); z0 = Math.min(z0, p.z); z1 = Math.max(z1, p.z); }
  polys.push({ tags, ring, x0, x1, z0, z1 });
}
const inside = (px, pz, ring) => { let c = false; for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) { const a = ring[i], b = ring[j]; if (a.z > pz !== b.z > pz && px < ((b.x - a.x) * (pz - a.z)) / (b.z - a.z) + a.x) c = !c; } return c; };

// footprint figures per cell (centroid of the ring decides the cell)
const fp = new Map();
for (const f of graph.footprints) {
  let cx = 0, cz = 0;
  for (const p of f.ring) { cx += p.x; cz += p.z; }
  cx /= f.ring.length; cz /= f.ring.length;
  const k = cellKey(Math.floor(cx / CELL), Math.floor(cz / CELL));
  let r = fp.get(k); if (!r) fp.set(k, (r = { area: 0, areas: [], levels: [] }));
  r.area += f.area; r.areas.push(f.area);
  const lv = Number(f.levels ?? f.tags?.['building:levels']); if (lv > 0) r.levels.push(lv);
}
const median = (a) => { if (!a.length) return 0; const s = [...a].sort((p, q) => p - q); return s[Math.floor(s.length / 2)]; };

const pct = (a, q) => { const s = [...a].sort((p, r) => p - r); return s[Math.min(s.length - 1, Math.floor(q * s.length))]; };
let X0 = Infinity, X1 = -Infinity, Z0 = Infinity, Z1 = -Infinity;
for (const p of pilot) { X0 = Math.min(X0, p.x); X1 = Math.max(X1, p.x); Z0 = Math.min(Z0, p.z); Z1 = Math.max(Z1, p.z); }
const ix0 = Math.floor(X0 / CELL), ix1 = Math.floor(X1 / CELL), iz0 = Math.floor(Z0 / CELL), iz1 = Math.floor(Z1 / CELL);
const names = [];
const rows = [];
const stat = {};
for (let iz = iz0; iz <= iz1; iz++) for (let ix = ix0; ix <= ix1; ix++) {
  const cx = ix * CELL + CELL / 2, cz = iz * CELL + CELL / 2;
  const osmTags = new Set();
  for (const p of polys) if (cx >= p.x0 && cx <= p.x1 && cz >= p.z0 && cz <= p.z1 && inside(cx, cz, p.ring)) for (const t of p.tags) osmTags.add(t);
  const f = fp.get(cellKey(ix, iz));
  const figures = { osm: [...osmTags], coverage: f ? Math.min(1, f.area / (CELL * CELL)) : 0, medianM2: f ? median(f.areas) : 0 };
  const arch = classifyCell(table, figures);
  let ni = names.indexOf(arch); if (ni < 0) { names.push(arch); ni = names.length - 1; }
  rows.push([ix, iz, ni]);
  if (inside(cx, cz, pilot)) {
    const s = (stat[arch] ??= { cells: 0, covSum: 0, medians: [], levels: [] });
    s.cells++; s.covSum += figures.coverage; if (figures.medianM2) s.medians.push(figures.medianM2); if (f) s.levels.push(...f.levels);
  }
}
const summary = {};
for (const [a, s] of Object.entries(stat)) summary[a] = { cells_in_pilot: s.cells, mean_coverage: Math.round((s.covSum / s.cells) * 1000) / 1000, median_footprint_m2: Math.round(median(s.medians) * 10) / 10, osm_levels_n: s.levels.length, osm_levels_median: s.levels.length ? median(s.levels) : null, osm_levels_p10: s.levels.length ? pct(s.levels, 0.1) : null, osm_levels_p90: s.levels.length ? pct(s.levels, 0.9) : null };
const out = {
  _doc: 'Archetype of every 100 m cell of the pilot centre box, by the rules in rules.json (P2-004). Generated by tools/bake/areas/derive.mjs from data/pilot_centre/osm.json (closed ways only) and graph.json footprints; do not edit by hand. rows are [ix, iz, archetypeIndex] with cell (ix, iz) holding x in [ix*100, ix*100+100) and z in [iz*100, iz*100+100) of the bake frame (origin India Gate, -z north). `summary` is the evidence the rule archetype profiles cite.',
  cell_m: CELL, archetypes: names, summary, rows,
};
const text = '{\n' + Object.entries(out).map(([k, v]) => k === 'rows' ? ` "rows": [\n${v.map((r) => '  ' + JSON.stringify(r)).join(',\n')}\n ]` : ` ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n') + '\n}\n';
console.log(JSON.stringify(summary, null, 1), 'cells', rows.length);
if (process.argv.includes('--write')) { fs.writeFileSync('harness/data/areas/rule_cells.json', text); console.log('written'); }
